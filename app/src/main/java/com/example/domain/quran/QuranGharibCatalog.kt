    fun extractForAyah(ayah: AyahItem): List<GharibWordEntry> {
        val normalizedBase = QuranRepository.normalizeArabic(ayah.imlaiText.ifBlank { ayah.text })
        if (normalizedBase.isBlank()) return emptyList()

        val tokens = normalizedBase
            .replace(PUNCT_REGEX, " ")
            .split(WHITESPACE_REGEX)
            .filter { it.length >= 2 }

        val matches = LinkedHashMap<String, GharibWordEntry>()
        for (token in tokens) {
            for (candidate in candidateForms(token)) {
                val entry = wordMeanings[candidate]
                if (entry != null) {
                    matches.putIfAbsent(entry.first, GharibWordEntry(entry.first, entry.second))
                    break
                }
            }
        }
        return matches.values.toList()
    }

    private fun candidateForms(token: String): List<String> = buildList {
        add(token)
        val prefixes = listOf("وال", "فال", "بال", "كال", "لل", "ال", "و", "ف", "ب", "ل", "ك", "ي", "ت", "ن")
        for (p in prefixes) {
            if (token.startsWith(p) && token.length - p.length >= 3) {
                add(token.removePrefix(p))
            }
        }
    }

    private val WHITESPACE_REGEX = Regex("\\s+")
    private val PUNCT_REGEX = Regex("[\\u06D6-\\u06ED۞۩۝،؛؟.,:;()\\[\\]{}]")
